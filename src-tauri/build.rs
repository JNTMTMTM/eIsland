fn main() {
    println!("cargo:rustc-check-cfg=cfg(coverage)");
    tauri_build::build();
    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc")
    {
        // Library test executables also link native dialogs, but do not receive the
        // desktop binary's resource manifest. Activate Common Controls v6 for both.
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTDEPENDENCY:type='win32' name='Microsoft.Windows.Common-Controls' version='6.0.0.0' processorArchitecture='*' publicKeyToken='6595b64144ccf1df' language='*'");
        // Tauri already supplies the desktop manifest in resource.lib. Keep that
        // resource instead of generating a second resource with the same ID.
        println!("cargo:rustc-link-arg-bin=eisland=/MANIFEST:NO");
    }
}
