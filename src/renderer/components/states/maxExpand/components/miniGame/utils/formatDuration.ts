/**
 * @file formatDuration.ts
 * @description 格式化小游戏成绩的用时。
 * @author 鸡哥
 */

/**
 * 将毫秒成绩转换成分钟和秒。
 * @param ms - 成绩用时，单位毫秒。
 * @returns 与原页面一致的用时文本。
 */
export function formatDuration(ms: number): string {
  const totalSec = Math.floor(ms / 1000);
  const m = Math.floor(totalSec / 60);
  const s = totalSec % 60;
  return m > 0 ? `${m}m ${s}s` : `${s}s`;
}
