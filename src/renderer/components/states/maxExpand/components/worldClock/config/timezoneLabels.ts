/**
 * 将 IANA 时区 ID 转为 i18n 键后缀（/ → _）
 * 例: "Asia/Shanghai" → "Asia_Shanghai"
 */
function tzKey(tz: string): string {
  return `maxExpand.worldClock.timezoneLabels.${tz.replace(/\//g, '_')}`;
}

